export function initPillarsAndServices() {
  const grid = document.getElementById('services-grid');
  const filterBtns = document.querySelectorAll('.filter-btn');

  function renderServices(filter = 'all') {
    if (!grid) return;
    grid.innerHTML = '';

    const filtered = filter === 'all' 
      ? SERVICES_DATA 
      : SERVICES_DATA.filter(s => s.category === filter);

    filtered.forEach((service, i) => {
      const card = document.createElement('div');
      card.className = 'service-card glass-card card-pop-in';
      card.style.animationDelay = `${Math.min(i, 10) * 0.05}s`;
      card.innerHTML = `
        <div class="service-header">
          <div class="service-icon">${service.icon}</div>
          <span class="service-number">${service.number}</span>
        </div>
        <h4 class="service-title">${service.title}</h4>
        <p class="service-desc">${service.desc}</p>
        <div class="service-tech-tags">
          ${service.technologies.map(t => `<span class="service-tech-tag">${t}</span>`).join('')}
        </div>
      `;
      grid.appendChild(card);
    });
  }

  // Filter Buttons
  filterBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      filterBtns.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      const filter = btn.getAttribute('data-filter') || 'all';
      renderServices(filter);
    });
  });

  // Initial render
  renderServices('all');
}
